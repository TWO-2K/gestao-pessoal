-- Catálogo padrão de produtos de uso residencial, disponível para todos os usuários.
-- Cada usuário (existente e novo) recebe os produtos no mercado "Geral", só com nome e setor.
-- Corredor/prateleira ficam em branco para o usuário preencher.

create table if not exists public.produtos_catalogo (
  nome text primary key,
  setor text
);

alter table public.produtos_catalogo enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'produtos_catalogo' and policyname = 'produtos_catalogo_read'
  ) then
    create policy produtos_catalogo_read on public.produtos_catalogo
      for select to authenticated using (true);
  end if;
end $$;

