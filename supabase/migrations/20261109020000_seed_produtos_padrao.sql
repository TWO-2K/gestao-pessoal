create or replace function public.seed_produtos_padrao(p_user_id uuid)
returns void
language sql
security definer
set search_path = public
as $fn$
  insert into public.produtos (nome, setor, local, user_id)
  select c.nome, c.setor, 'Geral', p_user_id
  from public.produtos_catalogo c
  on conflict (user_id, local, nome) do nothing;
$fn$;

revoke all on function public.seed_produtos_padrao(uuid) from public, anon, authenticated;

-- Usuários já existentes
select public.seed_produtos_padrao(id) from auth.users;

-- Novos usuários
create or replace function public.trg_seed_produtos_padrao()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
begin
  perform public.seed_produtos_padrao(new.id);
  return new;
end;
$fn$;

drop trigger if exists seed_produtos_padrao_on_signup on auth.users;
create trigger seed_produtos_padrao_on_signup
  after insert on auth.users
  for each row execute function public.trg_seed_produtos_padrao();
